#!/usr/bin/env node
// 重新生成所有提交进仓库的构建产物。
//
// 这个包把构建结果一起提交：只改可读源码而不重新生成 *.min.* 等于留下旧 bug。
// 源码 `lib/js/xqlight.js` 是唯一事实来源：
//   lib/js/xqlight.js     手写 UMD 源码
//   lib/js/xqlight.esm.mjs        由源码生成（可读 ESM）
//   lib/js/xqlight.min.js         UMD 压缩版
//   lib/js/xqlight.esm.min.mjs    ESM 压缩版
//   lib/css/xqlight.min.css       CSS 压缩版
//
// 用法：
//   node scripts/build.mjs            生成并写入
//   node scripts/build.mjs --check    只比较，不写盘；产物过期时退出码为 1

import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

const SOURCE = path.join(repo, 'lib', 'js', 'xqlight.js');
const CSS_SOURCE = path.join(repo, 'lib', 'css', 'xqlight.css');
const ESM = path.join(repo, 'lib', 'js', 'xqlight.esm.mjs');
const TARGETS = {
    umd: path.join(repo, 'lib', 'js', 'xqlight.min.js'),
    esm: path.join(repo, 'lib', 'js', 'xqlight.esm.min.mjs'),
    css: path.join(repo, 'lib', 'css', 'xqlight.min.css')
};

// UMD 包装的固定形状，ESM 构建从这两处切开。
const WRAPPER_OPEN = '})(typeof self !== \'undefined\' ? self : this, function () {';
const WRAPPER_TAIL = /\r?\n\s*return XqLightBox;\r?\n\}\);\s*$/;

// 由源码导出的具名符号。ESM 的 export 列表来自这里，顺序固定。
const NAMED_EXPORTS = [
    'XqLightBox',
    'ZOOM_STEP',
    'ZOOM_MIN',
    'ZOOM_MAX',
    'clampScale',
    'wrapIndex',
    'parseFileName',
    'buildFileName',
    'downloadImage',
    'toggleFullscreen',
    'exitFullscreen'
];

const pkg = JSON.parse(readFileSync(path.join(repo, 'package.json'), 'utf8'));
const version = pkg.version;

/**
 * 把源码里的版本号对齐到 package.json（唯一事实来源）。
 * @param {string} file
 * @returns {boolean} 是否有改动
 */
function syncVersion(file) {
    const source = readFileSync(file, 'utf8');
    const next = source
        .replace(/xqlight v\d+\.\d+\.\d+/g, 'xqlight v' + version)
        .replace(/(const VERSION = ')\d+\.\d+\.\d+(')/, '$1' + version + '$2');
    if (next === source) return false;
    console.log('  version -> ' + version + '  ' + path.relative(repo, file));
    if (!checkOnly) writeFileSync(file, next, 'utf8');
    return true;
}

/**
 * 从 UMD 源码里切出工厂函数体。
 * @param {string} source
 * @returns {{ header: string, body: string }}
 */
function splitSource(source) {
    const openAt = source.indexOf(WRAPPER_OPEN);
    if (openAt < 0) {
        throw new Error('Cannot find the UMD wrapper in lib/js/xqlight.js');
    }
    const header = source.slice(0, source.indexOf('(function (root, factory) {')).trimEnd();
    const body = source.slice(openAt + WRAPPER_OPEN.length);
    if (!WRAPPER_TAIL.test(body)) {
        throw new Error('Cannot find the factory tail (return XqLightBox;) in lib/js/xqlight.js');
    }
    return { header, body: body.replace(WRAPPER_TAIL, '\n') };
}

/**
 * 生成可读的 ESM 构建。
 * @param {string} header
 * @param {string} body
 * @returns {string}
 */
function buildEsm(header, body) {
    // 把生成标记插进原 banner 注释内部，而不是追加到注释结束符之后。
    const lines = header.replace(/xqlight v[\d.]+/, 'xqlight v' + version + ' (ES module build)').split('\n');
    const generated = ' * @generated by scripts/build.mjs from lib/js/xqlight.js — do not edit directly.';
    const closeAt = lines.findIndex(function (line) {
        return line.trim() === '*/';
    });
    if (closeAt > 0) lines.splice(closeAt, 0, generated);
    else lines.unshift('// @generated by scripts/build.mjs from lib/js/xqlight.js — do not edit directly.');

    // UMD 工厂体多缩进一层，去掉它让 ESM 产物读起来像普通模块。
    const flat = body.trim().replace(/\r\n/g, '\n').split('\n').map(function (line) {
        return line.startsWith('    ') ? line.slice(4) : line;
    }).join('\n');

    const exportsBlock = [
        'export {',
        NAMED_EXPORTS.map(function (name) {
            return '    ' + name;
        }).join(',\n'),
        '};',
        'export default XqLightBox;',
        ''
    ].join('\n');
    return lines.join('\n') + '\n' + flat + '\n\n' + exportsBlock;
}

/**
 * 找一个可用的 esbuild。
 * @returns {string|null}
 */
function findMinifier() {
    const bin = process.platform === 'win32' ? 'esbuild.cmd' : 'esbuild';
    const candidates = [
        process.env.XQLIGHT_MINIFIER,
        path.join(repo, 'node_modules', '.bin', bin),
        path.join(repo, 'node_modules', 'esbuild', 'bin', 'esbuild')
    ].filter(Boolean);
    for (const candidate of candidates) {
        if (candidate.includes(path.sep) && !existsSync(candidate)) continue;
        const probe = spawnSync(candidate, ['--version'], { encoding: 'utf8', shell: true });
        if (probe.status === 0) return candidate;
    }
    return null;
}

/**
 * 调用压缩器。
 * @param {string} bin
 * @param {string[]} args
 */
function run(bin, args) {
    const result = spawnSync(bin, args, { encoding: 'utf8', shell: true });
    if (result.status !== 0) {
        throw new Error(bin + ' failed:\n' + (result.stderr || result.stdout || ''));
    }
}

/**
 * 压缩单个文件并返回结果内容。始终先写到临时目录，--check 不会碰到仓库文件。
 *
 * UMD 产物不能传 --format=esm：esbuild 会把 `module.exports` 改写成 `export default`，
 * 让 `<script>` 直接加载失效。只有 ESM 产物才需要显式 format。
 *
 * @param {string} bin
 * @param {string} input
 * @param {string} work 临时目录
 * @param {string} name
 * @param {{ format?: string, css?: boolean }} shape
 * @returns {string}
 */
function minifyTo(bin, input, work, name, shape) {
    const outFile = path.join(work, name);
    const args = [input, '--minify', '--legal-comments=inline', '--outfile=' + outFile];
    if (shape.format) args.push('--format=' + shape.format);
    if (!shape.css) args.push('--target=es2017');
    run(bin, args);
    return readFileSync(outFile, 'utf8').trim() + '\n';
}

function main() {
    if (!existsSync(SOURCE)) {
        console.error('Missing source: ' + SOURCE);
        return 2;
    }

    console.log('xqlight build' + (checkOnly ? ' (check only)' : '') + ' — v' + version);
    let drift = false;
    drift = syncVersion(SOURCE) || drift;
    drift = syncVersion(CSS_SOURCE) || drift;

    const source = readFileSync(SOURCE, 'utf8');
    const { header, body } = splitSource(source);
    const esmSource = buildEsm(header, body);

    // 断言：ESM 真的把默认导出和具名导出接上了
    if (!/export default XqLightBox;/.test(esmSource) || !/export \{/.test(esmSource)) {
        throw new Error('Generated ESM build is missing its export block.');
    }

    const esmCurrent = existsSync(ESM) ? readFileSync(ESM, 'utf8') : '';
    if (esmCurrent.trim() !== esmSource.trim()) {
        drift = true;
        console.log('  ' + (checkOnly ? 'STALE   ' : 'write   ') + path.relative(repo, ESM));
        if (!checkOnly) writeFileSync(ESM, esmSource, 'utf8');
    }

    const minifier = findMinifier();
    if (!minifier) {
        console.error('No minifier found. Install esbuild ("npm i -D esbuild") or set XQLIGHT_MINIFIER.');
        return 2;
    }

    const work = mkdtempSync(path.join(tmpdir(), 'xqlight-build-'));
    const outputs = {
        umd: minifyTo(minifier, SOURCE, work, 'xqlight.min.js', {}),
        esm: minifyTo(minifier, ESM, work, 'xqlight.esm.min.mjs', { format: 'esm' }),
        css: minifyTo(minifier, CSS_SOURCE, work, 'xqlight.min.css', { css: true })
    };
    rmSync(work, { recursive: true, force: true });

    for (const key of Object.keys(outputs)) {
        const target = TARGETS[key];
        const next = outputs[key];
        const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
        const same = current.trim() === next.trim();
        if (!same) drift = true;
        console.log('  ' + (same ? 'in sync ' : checkOnly ? 'STALE   ' : 'write   ') + path.relative(repo, target));
        if (!same && !checkOnly) writeFileSync(target, next, 'utf8');
    }

    if (checkOnly) {
        console.log(drift ? '\nCommitted artifacts are stale; run "npm run build".' : '\nAll artifacts are in sync.');
        return drift ? 1 : 0;
    }
    console.log('\nBuild finished.');
    return 0;
}

try {
    process.exit(main());
} catch (error) {
    console.error(error && error.message ? error.message : error);
    process.exit(2);
}
